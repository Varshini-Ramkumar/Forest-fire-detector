// Generates 24 historical points for chart trends
export const GENERATE_INITIAL_READINGS = (): SensorReading[] => {
  const readings: SensorReading[] = [];
  const now = Date.now();
  for (let i = 24; i >= 0; i--) {
    const time = new Date(now - i * 3600 * 1000).toISOString();
    // Simulate natural diurnal curve: hottest at midday, humid in early morning
    const hour = new Date(now - i * 3600 * 1000).getHours();
    const tempOffset = Math.sin(((hour - 8) / 12) * Math.PI) * 10;
    const baseTemp = 28 + Math.max(0, tempOffset) + (Math.random() * 2 - 1);
    const baseHum = 70 - Math.max(0, tempOffset) * 2.2 + (Math.random() * 4 - 2);
    const baseSmoke = (i < 3 ? 45 : 16) + (Math.random() * 6 - 3);

    readings.push({
      id: `read-hist-${i}`,
      nodeId: 'SN-109',
      zoneId: 'zone-5',
      temperature: Math.round(baseTemp * 10) / 10,
      humidity: Math.max(15, Math.min(95, Math.round(baseHum))),
      smokeLevel: Math.max(5, Math.round(baseSmoke)),
      flameDetected: i <= 1,
      batteryLevel: Math.max(60, 95 - Math.round(i * 0.4)),
      timestamp: time,
    });
  }
  return readings;
};

